#!/bin/bash
# =====================================================================
# CONFIGURATION GENERATOR MODULE (utils/setup/env_generator.sh)
# =====================================================================
# Responsibility:
#   Generate non-sensitive runtime configuration files:
#     - configs/.env      (environment parameters, zero passwords)
#     - configs/ups.conf  (UPS driver & Low Battery safety overrides)
#     - configs/nut.conf  (restored if absent)
#     - configs/upsd.conf (restored if absent)
#
# Public API:
#   generate_env_file
#   generate_ups_conf
#   ensure_base_nut_configs
# =====================================================================

# ---------------------------------------------------------------------
# _apply_owner_and_mode: Restore non-root caller ownership (when run
# via sudo) and apply target UNIX file permissions.
# Arguments:
#   $1 - File path
#   $2 - Octal permission mode (e.g. "600", "644")
# ---------------------------------------------------------------------
_apply_owner_and_mode() {
    local filepath="$1"
    local mode="$2"

    if [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != "root" ]; then
        chown "$SUDO_USER" "$filepath" 2>/dev/null || true
    fi
    chmod "$mode" "$filepath"
}

# ---------------------------------------------------------------------
# generate_env_file: Write non-sensitive runtime variables to
# configs/.env with mode 600. Passwords are excluded by design.
# ---------------------------------------------------------------------
generate_env_file() {
    print_step "6/7" "Generating Runtime Environment" "Writing non-sensitive variables to configs/.env"

    local tz_val="${CONTAINER_TZ:-${TZ:-UTC}}"
    local nominal_line="# UPS_NOMINAL_WATTS="
    if [ -n "${UPS_NOMINAL_WATTS:-}" ]; then
        nominal_line="UPS_NOMINAL_WATTS=${UPS_NOMINAL_WATTS}"
    fi

    cat <<EOF > "$ENV_FILE"
# =====================================================================
# NUT SERVER ENVIRONMENT CONFIGURATION (configs/.env)
# Auto-generated by utils/setup.sh
# =====================================================================
# NOTE: Passwords are NOT stored in this file.
# They are managed via Docker Secrets in configs/secrets/ (RAM-mounted).

IMAGE_NAME=nut-server:local
CONTAINER_NAME=nut-server
TZ=${tz_val}

UPS_NAME=${UPS_NAME}
ALERT_LANG=${ALERT_LANG}
UPS_FRIENDLY_NAME="${UPS_FRIENDLY_NAME}"
# Optional fallback if your UPS does not report ups.realpower.nominal via USB
${nominal_line}
BATTERY_CHARGE_LOW=${BATTERY_CHARGE_LOW:-30}
BATTERY_RUNTIME_LOW=${BATTERY_RUNTIME_LOW:-300}
UPS_OFFDELAY=${UPS_OFFDELAY:-60}
UPS_ONDELAY=${UPS_ONDELAY:-70}

# NUT Role-Based Client Users
API_USER=${API_USER}
SECONDARY_USER=${SECONDARY_USER:-upsmon_client}

# SMTP Notification Settings
SMTP_PROVIDER=${SMTP_PROVIDER}
SMTP_HOST=${SMTP_HOST}
SMTP_PORT=${SMTP_PORT}
SMTP_TLS=${SMTP_TLS}
SMTP_STARTTLS=${SMTP_STARTTLS}
SMTP_AUTH=${SMTP_AUTH}
SMTP_USER=${SMTP_USER}
NOTIFICATION_EMAIL=${NOTIFICATION_EMAIL}
EOF

    _apply_owner_and_mode "$ENV_FILE" "600"
    echo -e "  ${GREEN}✔${RESET} Generated ${BOLD}${ENV_FILE}${RESET} (chmod 600)"
}

# ---------------------------------------------------------------------
# generate_ups_conf: Write NUT hardware driver configuration and Low
# Battery / shutdown delay overrides to configs/ups.conf.
# ---------------------------------------------------------------------
generate_ups_conf() {
    print_step "7/7" "Generating Driver Configuration" "Synchronizing driver and vendorid to configs/ups.conf"

    local vendor_line=""
    if [ -n "${VENDOR_ID:-}" ]; then
        vendor_line="    vendorid = \"${VENDOR_ID}\""
    fi

    local charge_low="${BATTERY_CHARGE_LOW:-30}"
    local runtime_low="${BATTERY_RUNTIME_LOW:-300}"
    local offdelay="${UPS_OFFDELAY:-60}"
    local ondelay="${UPS_ONDELAY:-$((offdelay + 10))}"

    cat <<EOF > "$UPS_CONF_FILE"
# =====================================================================
# NUT DRIVER CONFIGURATION (ups.conf)
# Auto-generated by utils/setup.sh
# =====================================================================

# Global driver parameters: retry connecting up to 3 times with 5s delay
maxretry = 3
retrydelay = 5

# UPS definition matching UPS_NAME defined in configs/.env
[${UPS_NAME}]
    driver = usbhid-ups
    port = auto
    desc = "${UPS_FRIENDLY_NAME}"
    pollinterval = 2
${vendor_line}
    # Enforce custom Low Battery (LB) thresholds instead of hardware defaults
    ignorelb
    override.battery.charge.low = ${charge_low}
    override.battery.runtime.low = ${runtime_low}
    # Delayed UPS outlet power-off (offdelay) and auto-restart (ondelay > offdelay)
    offdelay = ${offdelay}
    ondelay = ${ondelay}
EOF

    _apply_owner_and_mode "$UPS_CONF_FILE" "644"
    echo -e "  ${GREEN}✔${RESET} Generated ${BOLD}${UPS_CONF_FILE}${RESET} (chmod 644)"
}

# ---------------------------------------------------------------------
# ensure_base_nut_configs: Restore missing baseline nut.conf and
# upsd.conf files without overwriting existing user customizations.
# ---------------------------------------------------------------------
ensure_base_nut_configs() {
    local configs_dir="${CONFIGS_DIR:-$(dirname "$UPS_CONF_FILE")}"
    local nut_conf="${configs_dir}/nut.conf"
    local upsd_conf="${configs_dir}/upsd.conf"

    if [ ! -f "$nut_conf" ]; then
        cat <<'EOF' > "$nut_conf"
# =====================================================================
# NUT OPERATIONAL MODE CONFIGURATION (nut.conf)
# Sets the operating mode of Network UPS Tools.
# =====================================================================

# netserver: The system acts as a network server for the UPS and accepts client connections
MODE=netserver
EOF
        _apply_owner_and_mode "$nut_conf" "644"
        echo -e "  ${GREEN}✔${RESET} Restored missing ${BOLD}${nut_conf}${RESET} (chmod 644)"
    fi

    if [ ! -f "$upsd_conf" ]; then
        cat <<'EOF' > "$upsd_conf"
# =====================================================================
# NUT SERVER NETWORK & TLS CONFIGURATION (upsd.conf)
# Network listening addresses, access limits, and TLS certificate setup.
# =====================================================================

# Listen on all network interfaces on standard NUT port 3493
LISTEN 0.0.0.0 3493

# Timeouts and connection limits
MAXAGE 15
MAXCONN 1024

# TLS / SSL security configuration (NSS database)
CERTPATH /etc/nut/certs
CERTIDENT "nut-server" ""
EOF
        _apply_owner_and_mode "$upsd_conf" "644"
        echo -e "  ${GREEN}✔${RESET} Restored missing ${BOLD}${upsd_conf}${RESET} (chmod 644)"
    fi
}
