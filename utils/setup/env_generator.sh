#!/bin/bash
# =====================================================================
# CONFIGURATION GENERATOR MODULE (utils/setup/env_generator.sh)
# Generates non-sensitive environment variables file (configs/.env)
# and the NUT driver configuration (configs/ups.conf).
# =====================================================================

generate_env_file() {
    echo -e "${BOLD}--- 6. Generating configs/.env ---${RESET}"

    cat <<EOF > "$ENV_FILE"
# =====================================================================
# NUT SERVER ENVIRONMENT CONFIGURATION (configs/.env)
# Auto-generated by utils/setup.sh
# =====================================================================
# NOTE: Passwords are NOT stored in this file!
# They are managed via Docker Secrets in configs/secrets/ (mounted in RAM).

IMAGE_NAME=nut-server:local
CONTAINER_NAME=nut-server
TZ=Europe/Rome

UPS_NAME=$UPS_NAME
ALERT_LANG=$ALERT_LANG
UPS_FRIENDLY_NAME="$UPS_FRIENDLY_NAME"

API_USER=$API_USER

# SMTP Notification Settings
SMTP_PROVIDER=$SMTP_PROVIDER
SMTP_HOST=$SMTP_HOST
SMTP_PORT=$SMTP_PORT
SMTP_TLS=$SMTP_TLS
SMTP_STARTTLS=$SMTP_STARTTLS
SMTP_AUTH=$SMTP_AUTH
SMTP_USER=$SMTP_USER
NOTIFICATION_EMAIL=$NOTIFICATION_EMAIL
EOF

    if [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != "root" ]; then
        chown "$SUDO_USER" "$ENV_FILE" 2>/dev/null || true
    fi
    chmod 600 "$ENV_FILE"

    echo -e "  ${GREEN}✔${RESET} Generated ${BOLD}$ENV_FILE${RESET} (chmod 600)"
    echo ""
}

generate_ups_conf() {
    echo -e "${BOLD}--- 7. Generating configs/ups.conf ---${RESET}"

    local vendor_line=""
    if [ -n "$VENDOR_ID" ]; then
        vendor_line="    vendorid = \"$VENDOR_ID\""
    fi

    cat <<EOF > "$UPS_CONF_FILE"
# =====================================================================
# NUT DRIVER CONFIGURATION (ups.conf)
# Auto-generated by utils/setup.sh
# =====================================================================

# Global driver parameters: retry connecting up to 3 times with 5s delay
maxretry = 3
retrydelay = 5

# UPS definition matching UPS_NAME defined in configs/.env
[$UPS_NAME]
    driver = usbhid-ups
    port = auto
    desc = "$UPS_FRIENDLY_NAME"
    pollinterval = 2
$vendor_line
EOF

    if [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != "root" ]; then
        chown "$SUDO_USER" "$UPS_CONF_FILE" 2>/dev/null || true
    fi
    chmod 644 "$UPS_CONF_FILE"

    echo -e "  ${GREEN}✔${RESET} Generated ${BOLD}$UPS_CONF_FILE${RESET} (chmod 644)"
    echo ""
}
